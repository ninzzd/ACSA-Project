"""
FakeRAM45-style 1R1W score-bank macro: fakeram45_256x512_1r1w (16 KB, 256 rows x 512 b).

The official FakeRAM45 set (OpenROAD-flow-scripts, flow/platforms/nangate45/lib) has only
single-port (1RW) macros, and the generator (bsg_fakeram + CACTI) was not run here. This
script writes a liberty + Verilog blackbox with the FakeRAM45 conventions:
  pins    clk, r_ce_in, r_addr_in, rd_out, w_ce_in, w_addr_in, wd_in, w_mask_in
  timing  copied from fakeram45_128x256: clk->rd_out 0.302 ns, setup/hold 0.050 ns,
          min_period 0.293 ns
  area    4 x fakeram45_128x256 = the official 16 KB single-port equivalent.
          A real 1R1W (8T cell + second decoder) is larger: see README / spec.
Usage: python3 gen_fakeram45_1r1w.py [outdir]
"""
import os
import sys

NAME, DEPTH, W = "fakeram45_256x512_1r1w", 256, 512
AW = (DEPTH - 1).bit_length()
AREA_128x256 = 33990.259                 # fakeram45_128x256.lib, um^2
AREA = 4 * AREA_128x256
T_CQ, T_SU, T_HD, T_MIN = 0.302, 0.050, 0.050, 0.293


def constraint(rel="clk"):
    out = []
    for kind, v in (("setup_rising", T_SU), ("hold_rising", T_HD)):
        out.append(f"""        timing() {{
            related_pin : {rel};
            timing_type : {kind};
            rise_constraint(scalar) {{ values ("{v:.3f}"); }}
            fall_constraint(scalar) {{ values ("{v:.3f}"); }}
        }}""")
    return "\n".join(out)


def in_pin(name, bus=None):
    head = f"bus({name})" if bus else f"pin({name})"
    bt = f"\n        bus_type : {NAME}_{bus};" if bus else ""
    return f"""    {head} {{{bt}
        direction : input;
        capacitance : 5.000;
{constraint()}
    }}"""


def lib():
    return f"""library({NAME}) {{
    technology (cmos);
    delay_model : table_lookup;
    comment : "FakeRAM45-style 1R1W blackbox; timing from fakeram45_128x256, area = 4 x fakeram45_128x256";
    time_unit : "1ns";
    voltage_unit : "1V";
    current_unit : "1uA";
    leakage_power_unit : "1nw";
    capacitive_load_unit (1,ff);
    pulling_resistance_unit : "1kohm";
    nom_process : 1;
    nom_temperature : 25.000;
    nom_voltage : 1.1;
    operating_conditions(tt_1.0_25.0) {{
        process : 1;
        temperature : 25.000;
        voltage : 1.1;
    }}
    default_operating_conditions : tt_1.0_25.0;
    default_max_transition : 0.227;
    input_threshold_pct_rise : 50.000;
    input_threshold_pct_fall : 50.000;
    output_threshold_pct_rise : 50.000;
    output_threshold_pct_fall : 50.000;
    slew_lower_threshold_pct_rise : 20.000;
    slew_lower_threshold_pct_fall : 20.000;
    slew_upper_threshold_pct_rise : 80.000;
    slew_upper_threshold_pct_fall : 80.000;
    lu_table_template({NAME}_slew) {{
        variable_1 : total_output_net_capacitance;
        index_1 ("1000, 1001");
    }}
    type ({NAME}_DATA) {{
        base_type : array; data_type : bit; bit_width : {W}; bit_from : {W - 1}; bit_to : 0; downto : true;
    }}
    type ({NAME}_ADDRESS) {{
        base_type : array; data_type : bit; bit_width : {AW}; bit_from : {AW - 1}; bit_to : 0; downto : true;
    }}
cell({NAME}) {{
    area : {AREA:.3f};
    interface_timing : true;
    dont_use : true;
    dont_touch : true;
    pin(clk) {{
        direction : input;
        capacitance : 25.000;
        clock : true;
        min_period : {T_MIN:.3f};
    }}
    bus(rd_out) {{
        bus_type : {NAME}_DATA;
        direction : output;
        max_capacitance : 500.000;
        timing() {{
            related_pin : "clk";
            timing_type : rising_edge;
            timing_sense : non_unate;
            cell_rise(scalar) {{ values ("{T_CQ:.3f}"); }}
            cell_fall(scalar) {{ values ("{T_CQ:.3f}"); }}
            rise_transition({NAME}_slew) {{ index_1 ("5.000, 500.000"); values ("0.009, 0.227"); }}
            fall_transition({NAME}_slew) {{ index_1 ("5.000, 500.000"); values ("0.009, 0.227"); }}
        }}
    }}
{in_pin("r_ce_in")}
{in_pin("r_addr_in", "ADDRESS")}
{in_pin("w_ce_in")}
{in_pin("w_addr_in", "ADDRESS")}
{in_pin("wd_in", "DATA")}
{in_pin("w_mask_in", "DATA")}
}}
}}
"""


def verilog():
    return f"""// {NAME} -- blackbox (FakeRAM45-style 1R1W, generated by gen_fakeram45_1r1w.py)
(* blackbox *)
module {NAME} (
  input              clk,
  input              r_ce_in,
  input  [{AW - 1}:0]      r_addr_in,
  output [{W - 1}:0]    rd_out,
  input              w_ce_in,
  input  [{AW - 1}:0]      w_addr_in,
  input  [{W - 1}:0]    wd_in,
  input  [{W - 1}:0]    w_mask_in
);
endmodule
"""


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(out, NAME + ".lib"), "w") as f:
        f.write(lib())
    with open(os.path.join(out, NAME + ".v"), "w") as f:
        f.write(verilog())
    print(f"{NAME}: area {AREA:.1f} um^2, clk->q {T_CQ} ns")
